export const acceptanceValid = (
  rate:
    | "flexible"
    | "nonref",

  adult:
    boolean,

  terms:
    boolean,

  nonref:
    boolean
) =>
  adult &&
  terms &&
  (
    rate ===
      "flexible" ||
    nonref
  );

export function feeBreakdown(
  total:
    number,

  nights:
    number,

  perNight:
    number
) {
  const fee =
    Math.min(
      total,

      Math.max(
        0,

        Math.round(
          perNight *
            nights *
            100
        ) /
          100
      )
    );

  return {
    accommodation:
      Math.round(
        (
          total -
          fee
        ) *
          100
      ) /
        100,

    fee,

    total,
  };
}

export function refundForReason(
  total:
    number,

  rate:
    | "flexible"
    | "nonref",

  days:
    number,

  reason:
    | "guest"
    | "host"
    | "no-show"
    | "early-departure"
) {
  return reason ===
    "host"
    ? total
    : reason !==
        "guest" ||
      rate ===
        "nonref"
    ? 0
    : days >=
      21
    ? total
    : total /
      2;
}

export const reviewEligible = (
  b: {
    status:
      string;

    checkOut:
      string;
  },

  today:
    string,

  hour:
    number
) =>
  b.status ===
    "confirmed" &&
  (
    b.checkOut <
      today ||
    (
      b.checkOut ===
        today &&
      hour >=
        11
    )
  );
